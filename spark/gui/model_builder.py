        for name, node in self.canvas.nodes.items():
            nodes.append({
                'name': name,
                'x': float(node.pos().x()),
                'y': float(node.pos().y()),
                'is_initial': getattr(node, 'is_initial', False),
                'is_dark': getattr(node, 'is_dark', False)
            })
