class StateNode(QGraphicsRectItem):
    """Graphical box representing a physical kinetic state."""
    def __init__(self, name, x, y):
        super().__init__(-45, -20, 90, 40)
        self.name = name
        
        self.is_dark = False
        self.is_initial = False

        self.setPos(x, y)
        self.setFlag(QGraphicsItem.ItemIsMovable)
        self.setFlag(QGraphicsItem.ItemIsSelectable)
        self.setFlag(QGraphicsItem.ItemSendsGeometryChanges)
        
        self.text = QGraphicsTextItem(name, self)
        self.text.setFont(QFont("Segoe UI", 10, QFont.Bold))
        self.text.setDefaultTextColor(Qt.white)
        self.edges = [] 
        
        self.update_visuals()

    def update_visuals(self):
        if self.is_dark:
            color = QColor("#495057")
        else:
            color = QColor("#28A745" if not self.isSelected() else "#0078D7")
            
        self.setBrush(QBrush(color))
        
        pen_width = 3 if self.is_initial else 1.5
        pen_color = QColor("#FFC107") if self.is_initial else Qt.black
        self.setPen(QPen(pen_color, pen_width))
        
        self.text.setPlainText(self.name)
        br = self.text.boundingRect()
        self.text.setPos(-br.width()/2, -br.height()/2)

    def add_edge(self, edge):
        self.edges.append(edge)

    def itemChange(self, change, value):
        if change == QGraphicsItem.ItemPositionHasChanged:
            for edge in self.edges:
                edge.update_position()
        elif change == QGraphicsItem.ItemSelectedHasChanged:
            self.update_visuals()
        return super().itemChange(change, value)


class TransitionEdge(QGraphicsLineItem):
    """Smart graphical arrow connecting two StateNodes, supports bidirectionality."""
    def __init__(self, source_node, target_node, param_type, label):
        super().__init__()
        self.source_node = source_node
        self.target_node = target_node
        self.param_type = param_type
        self.label_name = label
        
        self.setPen(QPen(QColor("#2B2B2B"), 2, Qt.SolidLine, Qt.RoundCap, Qt.RoundJoin))
        self.setZValue(-1) 
        self.setFlag(QGraphicsItem.ItemIsSelectable)
        
        self.text = QGraphicsTextItem("", self)
        self.text.setFont(QFont("Segoe UI", 9, QFont.Bold))
        
        self.source_node.add_edge(self)
        self.target_node.add_edge(self)
        self.update_visuals()

    def update_visuals(self):
        color = QColor("#DC3545") if self.isSelected() else QColor("#0078D7")
        self.text.setDefaultTextColor(color)
        
        symbol = "k" if self.param_type == "rate (k)" else ("τ" if self.param_type == "tau" else "γ")
        self.text.setPlainText(f"{self.label_name} ({symbol})")
        self.update_position()

    def update_position(self):
        base_line = QLineF(self.source_node.pos(), self.target_node.pos())
        is_bidirectional = any(e for e in self.target_node.edges if e.target_node == self.source_node)
        
        if is_bidirectional:
            angle = math.atan2(base_line.dy(), base_line.dx())
            offset = 12 
            dx = math.sin(angle) * offset
            dy = -math.cos(angle) * offset
            base_line.translate(dx, dy)

        self.setLine(base_line)
        center = base_line.center()
        self.text.setPos(center.x() - self.text.boundingRect().width()/2, 
                         center.y() - self.text.boundingRect().height() - 5)

    def itemChange(self, change, value):
        if change == QGraphicsItem.ItemSelectedHasChanged:
            self.update_visuals()
        return super().itemChange(change, value)

    def paint(self, painter, option, widget=None):
        color = QColor("#DC3545") if self.isSelected() else QColor("#2B2B2B")
        pen = QPen(color, 2, Qt.SolidLine, Qt.RoundCap, Qt.RoundJoin)
        painter.setPen(pen)
        painter.drawLine(self.line())
        
        line = self.line()
        if line.length() > 0:
            center = line.center()
            angle = math.atan2(line.dy(), line.dx())
            arrow_size = 12
            p1 = center - QPointF(math.cos(angle - math.pi / 6) * arrow_size, math.sin(angle - math.pi / 6) * arrow_size)
            p2 = center - QPointF(math.cos(angle + math.pi / 6) * arrow_size, math.sin(angle + math.pi / 6) * arrow_size)
            painter.setBrush(QBrush(color))
            painter.drawPolygon(QPolygonF([center, p1, p2]))


