class KineticCanvas(QGraphicsView):
    connection_added = pyqtSignal() 

    def __init__(self):
        super().__init__()
        self.scene = QGraphicsScene(self)
        self.scene.setSceneRect(0, 0, 1000, 800)
        self.setScene(self.scene)
        self.setRenderHint(QPainter.Antialiasing)
        
        self.nodes = {} 
        self.linking_mode = False
        self.link_source = None
        
    def add_state(self, name, x=None, y=None):
        if name in self.nodes:
            QMessageBox.warning(self, "Warning", f"State '{name}' already exists.")
            return None
        offset = len(self.nodes) * 70
        node = StateNode(name, x if x else 150 + offset, y if y else 100 + offset)
        
        if len(self.nodes) == 0:
            node.is_initial = True
            node.update_visuals()
            
        self.scene.addItem(node)
        self.nodes[name] = node
        return node

    def delete_selected(self):
        for item in self.scene.selectedItems():
            if hasattr(item, 'parentItem') and item.parentItem() is not None:
                item = item.parentItem()
                
            if isinstance(item, StateNode):
                for edge in list(item.edges):
                    if edge in self.scene.items(): self.scene.removeItem(edge)
                    if edge in edge.source_node.edges: edge.source_node.edges.remove(edge)
                    if edge in edge.target_node.edges: edge.target_node.edges.remove(edge)
                    for e in edge.target_node.edges + edge.source_node.edges:
                        if isinstance(e, TransitionEdge): e.update_position()
                        
                if item.name in self.nodes: del self.nodes[item.name]
                if item in self.scene.items(): self.scene.removeItem(item)
                    
            elif isinstance(item, TransitionEdge):
                if item in item.source_node.edges: item.source_node.edges.remove(item)
                if item in item.target_node.edges: item.target_node.edges.remove(item)
                if item in self.scene.items(): self.scene.removeItem(item)
                for e in item.target_node.edges + item.source_node.edges:
                    if isinstance(e, TransitionEdge): e.update_position()

    def mousePressEvent(self, event):
        item = self.itemAt(event.pos())
        
        clicked_node = None
        for node in self.nodes.values():
            if item == node or item == node.text:
                clicked_node = node
                break
                
        if self.linking_mode:
            if clicked_node:
                if self.link_source is None:
                    self.link_source = clicked_node
                    clicked_node.setBrush(QBrush(QColor("#0078D7"))) 
                else:
                    if self.link_source != clicked_node:
                        edge = TransitionEdge(self.link_source, clicked_node, "tau", f"t{len(self.scene.items())}")
                        self.scene.addItem(edge)
                        for e in self.link_source.edges: e.update_position()
                        self.connection_added.emit() 
                        
                    self.link_source.update_visuals()
                    self.link_source = None
                    self.linking_mode = False
            else:
                if self.link_source: self.link_source.update_visuals()
                self.link_source = None
                self.linking_mode = False
                
        super().mousePressEvent(event)


