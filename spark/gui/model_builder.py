    def on_selection_changed(self):
        items = self.canvas.scene.selectedItems()
        self.edit_name.blockSignals(True)
        self.combo_type.blockSignals(True)
        self.chk_initial.blockSignals(True)
        self.chk_dark.blockSignals(True)
        
        if not items:
            self.lbl_prop_type.setText("<i>Select a state or connection</i>")
            self.edit_name.clear(); self.edit_name.setEnabled(False)
            self.combo_type.setEnabled(False)
            self.chk_initial.setEnabled(False); self.chk_initial.setChecked(False)
            self.chk_dark.setEnabled(False); self.chk_dark.setChecked(False)
        else:
            item = items[0]
            if hasattr(item, 'parentItem') and item.parentItem() is not None: item = item.parentItem()
            self.edit_name.setEnabled(True)
            
            if isinstance(item, StateNode):
                self.lbl_prop_type.setText("<b>State Node Selected</b>")
                self.edit_name.setText(item.name)
                self.combo_type.setEnabled(False)
                self.chk_initial.setEnabled(True); self.chk_initial.setChecked(item.is_initial)
                self.chk_dark.setEnabled(True); self.chk_dark.setChecked(item.is_dark)
                
